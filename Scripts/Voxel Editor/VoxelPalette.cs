using UnityEngine;

// Палитра в духе MagicaVoxel — 96 цветов (в UI редактора: 6 рядов по 16):
//   0..47  — 12 тонов x 4 ряда светлоты (пастель -> тёмные)
//  48..55  — градации серого: чёрный -> белый
//  56..67  — 12 промежуточных тонов (шаг 15 градусов)
//  68..75  — земля и кожа: коричневые, загар, оливковый, терракота, песок
//  76..83  — 8 глубоких тёмных цветов
//  84..91  — 8 ярких насыщенных цветов
//  92..95  — золото, серебро, тёмный бирюзовый, кремовый
public static class VoxelPalette
{
    public const int Size = 96;

    public static Color32[] Default()
    {
        var p = new Color32[Size];

        // 0..47 — основная сетка: 12 тонов x 4 ряда светлоты.
        for (int i = 0; i < 48; i++)
        {
            float hue = (i % 12) / 12f;
            float s, v;
            switch (i / 12)
            {
                case 0:  s = 0.30f; v = 1.00f; break; // пастельные
                case 1:  s = 0.70f; v = 0.95f; break; // чистые
                case 2:  s = 0.95f; v = 0.72f; break; // насыщенные потемнее
                default: s = 0.85f; v = 0.42f; break; // тёмные
            }
            p[i] = Color.HSVToRGB(hue, s, v);
        }

        // 48..55 — градации серого.
        for (int i = 0; i < 8; i++)
        {
            float g = i / 7f;
            p[48 + i] = new Color(g, g, g);
        }

        // 56..67 — 12 промежуточных тонов (смещены на 15 градусов относительно основных).
        for (int i = 0; i < 12; i++)
        {
            float hue = (i + 0.5f) / 12f;
            p[56 + i] = Color.HSVToRGB(hue, 0.80f, 0.85f);
        }

        // 68..75 — земля и кожа.
        Color[] earth =
        {
            new Color(0.36f, 0.25f, 0.20f), // тёмно-коричневый
            new Color(0.55f, 0.38f, 0.26f), // коричневый
            new Color(0.70f, 0.52f, 0.35f), // охра
            new Color(0.90f, 0.72f, 0.56f), // кожа
            new Color(0.98f, 0.86f, 0.73f), // светлая кожа
            new Color(0.55f, 0.50f, 0.25f), // оливковый
            new Color(0.78f, 0.45f, 0.30f), // терракота
            new Color(0.88f, 0.78f, 0.58f), // песочный
        };
        for (int i = 0; i < earth.Length; i++) p[68 + i] = earth[i];

        // 76..83 — глубокие тёмные (8 тонов с шагом 45 градусов).
        for (int i = 0; i < 8; i++)
            p[76 + i] = Color.HSVToRGB(i / 8f, 0.85f, 0.25f);

        // 84..91 — яркие насыщенные.
        for (int i = 0; i < 8; i++)
            p[84 + i] = Color.HSVToRGB(i / 8f, 1.0f, 1.0f);

        // 92..95 — бонусные цвета.
        p[92] = new Color(1.00f, 0.84f, 0.10f); // золото
        p[93] = new Color(0.72f, 0.76f, 0.82f); // серебро
        p[94] = new Color(0.06f, 0.32f, 0.34f); // тёмный бирюзовый
        p[95] = new Color(1.00f, 0.97f, 0.88f); // кремовый

        return p;
    }
}